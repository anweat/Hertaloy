import { createRequire } from 'node:module';
import { resolve, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname } from 'node:path';
const __dirname = dirname(fileURLToPath(import.meta.url));
const pluginRoot = 'C:/Users/anwea/.understand-anything/repo/understand-anything-plugin';
const require = createRequire(resolve(pluginRoot, 'package.json'));
const core = await import(pathToFileURL(require.resolve('@understand-anything/core')).href);
const { TreeSitterPlugin, PluginRegistry, builtinLanguageConfigs, registerAllParsers } = core;
const tsConfigs = builtinLanguageConfigs.filter(c => c.treeSitter);
console.log('tsConfigs:', tsConfigs.map(c => c.id || c.name));
const tsPlugin = new TreeSitterPlugin(tsConfigs);
await tsPlugin.init();
const registry = new PluginRegistry();
registry.register(tsPlugin);
registerAllParsers(registry);
const content = require('node:fs').readFileSync('D:/codeproject/Hertaloy/packages/kernel/src/store.ts','utf8');
const analysis = registry.analyzeFile('packages/kernel/src/store.ts', content);
console.log('analysis keys:', Object.keys(analysis || {}));
console.log('imports count:', analysis?.imports?.length);
console.log('imports:', JSON.stringify(analysis?.imports, null, 2).slice(0, 2000));
